import { useLayoutEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import { fmtNum } from '../lib/format';
import { Icon } from './Icon';
import { Sheet } from './Sheet';

/**
 * Number selection, Alpha-Progression style: a list of big value buttons stepping by `step`,
 * opened centred on the current value (tap = pick), plus a keypad for any custom value.
 *
 * Performance rules (the old scroll wheel felt heavy because it broke them):
 * - no scroll listener at all: the list is plain native scrolling, no snapping, no mask on the scroller;
 *   the highlight comes from the `value` prop, so scrolling never touches React state.
 * - rows are generated by index (no float drift) and capped to a window around the current value;
 *   values outside it are one keypad entry away.
 * - centring runs once per list (mount, or when step/unit changes), never during a scroll.
 */
export interface NumberSpec {
  min: number;
  max: number;
  step: number;
  /** Max decimals the keypad accepts (0 = whole numbers). Default: decimals of `step`. */
  decimals?: number;
  /** Row / display label. Default fmtNum + unit. */
  format?: (v: number) => string;
  unit?: string;
  /** Keypad bounds when they differ from the list's (e.g. list to 400 kg, keypad to 1000). */
  keyMin?: number;
  keyMax?: number;
  /** false = list only (short or labelled lists such as weekly rate). */
  keypad?: boolean;
  /** false = keypad only (doses: no sensible step). */
  list?: boolean;
}

const WINDOW = 120; // rows either side of the current value

const decimalsOf = (n: number) => { const s = String(n); const i = s.indexOf('.'); return i < 0 ? 0 : s.length - i - 1; };
const round = (v: number, d: number) => Math.round(v * 10 ** d) / 10 ** d;

export function buildValues(spec: NumberSpec, anchor: number | null | undefined, value?: number | null): number[] {
  const { min, max, step } = spec;
  const d = Math.max(decimalsOf(step), decimalsOf(min));
  const count = Math.floor((max - min) / step + 1e-9) + 1;
  const center = anchor == null || !Number.isFinite(anchor) ? 0 : Math.round((anchor - min) / step);
  const lo = Math.max(0, Math.min(count - 1, center) - WINDOW);
  const hi = Math.min(count - 1, Math.max(0, center) + WINDOW);
  const out: number[] = [];
  for (let i = lo; i <= hi; i++) out.push(round(min + i * step, d));
  // a current value that isn't on the grid (e.g. 60 kg shown in lb = 132.28) still gets its own row
  if (value != null && Number.isFinite(value) && !out.some((v) => Math.abs(v - value) < 1e-6)) {
    out.push(value);
    out.sort((a, b) => a - b);
  }
  return out;
}

export function NumberPicker({ value, onPick, spec, ariaLabel, inline }: {
  value: number | null | undefined; onPick: (v: number) => void; spec: NumberSpec; ariaLabel: string;
  /** inline (on a page): shorter list, picks don't close anything */
  inline?: boolean;
}) {
  const fmt = spec.format ?? ((v: number) => `${fmtNum(v)}${spec.unit ? ` ${spec.unit}` : ''}`);
  const showList = spec.list !== false;
  const showPad = spec.keypad !== false;
  // the row window is anchored where the picker opened, so inline picks don't shift the list
  const [anchor, setAnchor] = useState(value);
  const spanOk = anchor != null && value != null && Math.abs(value - anchor) <= WINDOW * spec.step * 0.8;
  if (value != null && !spanOk && value !== anchor) setAnchor(value);
  const values = useMemo(() => (showList ? buildValues(spec, anchor, value) : []),
    [showList, spec.min, spec.max, spec.step, anchor, value]); // rebuilt on a pick or a grid change, never on scroll
  const listRef = useRef<HTMLDivElement>(null);
  const selIdx = value == null ? -1 : values.findIndex((v) => Math.abs(v - value) < 1e-6);

  // Centre the current value once the list is laid out (the sheet's slide-in is a transform, so
  // layout is final on mount). Again only when the grid changes (step/unit switch, new window),
  // never when an inline pick just moves the highlight.
  const gridKey = `${spec.min}|${spec.max}|${spec.step}|${anchor}`;
  const centredKey = useRef<string | null>(null);
  useLayoutEffect(() => {
    const el = listRef.current;
    if (!el || centredKey.current === gridKey) return;
    centredKey.current = gridKey;
    let i = selIdx;
    if (i < 0 && value != null && values.length) { i = 0; for (let j = 1; j < values.length; j++) if (Math.abs(values[j] - value) < Math.abs(values[i] - value)) i = j; }
    const row = i >= 0 ? (el.children[i] as HTMLElement | undefined) : undefined;
    if (row) el.scrollTop = row.offsetTop - (el.clientHeight - row.offsetHeight) / 2;
  });

  return (
    <div className={'np' + (inline ? ' np-inline' : '') + (showList ? '' : ' np-padonly')}>
      {showList && (
        <div ref={listRef} className="np-list" role="group" aria-label={ariaLabel}>
          {values.map((v, i) => (
            <button key={v} type="button" className={'np-row num' + (i === selIdx ? ' on' : '')} aria-pressed={i === selIdx} onClick={() => onPick(v)}>
              {fmt(v)}
            </button>
          ))}
        </div>
      )}
      {showPad && <Keypad spec={spec} fmt={fmt} value={value} onPick={onPick} ariaLabel={ariaLabel} />}
    </div>
  );
}

function Keypad({ spec, fmt, value, onPick, ariaLabel }: {
  spec: NumberSpec; fmt: (v: number) => string; value: number | null | undefined; onPick: (v: number) => void; ariaLabel: string;
}) {
  const [typed, setTyped] = useState('');
  const dec = spec.decimals ?? decimalsOf(spec.step);
  const lo = spec.keyMin ?? spec.min, hi = spec.keyMax ?? spec.max;
  const n = typed === '' || typed === '.' ? NaN : parseFloat(typed);
  const err = !Number.isFinite(n) ? null : n < lo ? `Min ${fmtNum(lo)}` : n > hi ? `Max ${fmtNum(hi)}` : null;
  const ok = Number.isFinite(n) && !err;

  const press = (k: string) => {
    if (k === 'del') return setTyped((t) => t.slice(0, -1));
    setTyped((t) => {
      if (k === '.') return dec === 0 || t.includes('.') ? t : (t === '' ? '0.' : t + '.');
      const next = t === '0' ? k : t + k;
      const i = next.indexOf('.');
      if (i >= 0 && next.length - i - 1 > dec) return t; // decimals only where allowed
      if (next.replace('.', '').length > 7) return t;
      return next;
    });
  };
  const commit = () => { if (ok) { onPick(round(n, dec)); setTyped(''); } };

  // hardware keyboard (desktop / iPad keyboard): digits, dot/comma, Backspace, Enter
  const onKey = (e: React.KeyboardEvent) => {
    const k = e.key;
    if (/^[0-9]$/.test(k)) press(k);
    else if (k === '.' || k === ',') press('.');
    else if (k === 'Backspace') press('del');
    else if (k === 'Enter' && typed) commit();
    else return;
    e.preventDefault();
  };

  const keys = ['1', '2', '3', '4', '5', '6', '7', '8', '9', '.', '0', 'del'];
  return (
    <div className="np-pad" onKeyDown={onKey}>
      <div className="np-entry">
        <output className={'np-display num' + (typed ? '' : ' empty') + (err ? ' bad' : '')} aria-live="polite" aria-label={`Typed ${ariaLabel.toLowerCase()}`}>
          {typed ? `${typed}${spec.unit ? ` ${spec.unit}` : ''}` : value != null ? fmt(value) : '–'}
        </output>
        <button type="button" className="np-ok" aria-label={ok ? `Set ${fmt(round(n, dec))}` : 'Set typed value'} disabled={!ok} onClick={commit}>
          <Icon name="check" size={24} stroke={2.8} />
        </button>
      </div>
      <div className="np-err" role="status">{err ?? ''}</div>
      <div className="np-keys">
        {keys.map((k) => (
          <button key={k} type="button" className="np-key num" onClick={() => press(k)}
            disabled={k === '.' && dec === 0} aria-label={k === 'del' ? 'Delete digit' : k === '.' ? 'Decimal point' : undefined}>
            {k === 'del' ? <BackspaceGlyph /> : k}
          </button>
        ))}
      </div>
    </div>
  );
}

const BackspaceGlyph = () => (
  <svg width={26} height={26} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
    <path d="M21 5H9l-6 7 6 7h12a1 1 0 0 0 1-1V6a1 1 0 0 0-1-1zM12.5 9.5l5 5M17.5 9.5l-5 5" />
  </svg>
);

/** Sheet version: tap a value (or ✓ a typed one) → onPick, then the sheet closes. */
export function NumberSheet({ open, onClose, title, value, onPick, spec, extra, footer }: {
  open: boolean; onClose: () => void; title: string; value: number | null | undefined; onPick: (v: number) => void;
  spec: NumberSpec; extra?: ReactNode; footer?: ReactNode;
}) {
  return (
    <Sheet open={open} onClose={onClose} title={title}>
      {/* the list shrinks by what extra/footer take, so the sheet never needs its own scroll */}
      <div className="stack" style={{ gap: 12, ['--np-reserve' as string]: `${(extra ? 92 : 0) + (footer ? 62 : 0)}px` }}>
        {extra}
        <NumberPicker value={value} spec={spec} ariaLabel={title} onPick={(v) => { onPick(v); onClose(); }} />
        {footer}
      </div>
    </Sheet>
  );
}

/** List row showing a number; opens a NumberSheet. Drop-in for the old numeric PickerRow. */
export function NumberRow({ label, sub, value, onChange, spec, title, icon, empty = '–' }: {
  label: string; sub?: string; value: number | null | undefined; onChange: (v: number) => void; spec: NumberSpec;
  title?: string; icon?: ReactNode; empty?: string;
}) {
  const [open, setOpen] = useState(false);
  const fmt = spec.format ?? ((v: number) => `${fmtNum(v)}${spec.unit ? ` ${spec.unit}` : ''}`);
  return (
    <>
      <button type="button" className="list-item pressable" onClick={() => setOpen(true)} aria-haspopup="dialog">
        {icon}
        <span className="grow"><span className="title">{label}</span>{sub && <span className="sub" style={{ display: 'block' }}>{sub}</span>}</span>
        <span className="picker-value num">{value == null ? empty : fmt(value)}</span>
        <Icon name="chevronRight" className="chev" size={18} />
      </button>
      <NumberSheet open={open} onClose={() => setOpen(false)} title={title ?? label} value={value} onPick={onChange} spec={spec} />
    </>
  );
}

/** Form-field version (looks like an input): label above, tap opens the sheet. */
export function NumberField({ label, value, onChange, spec, title, placeholder, style, compact }: {
  label: string; value: number | null | undefined; onChange: (v: number) => void; spec: NumberSpec;
  title?: string; placeholder?: string; style?: React.CSSProperties; /** no visible label (still named) */ compact?: boolean;
}) {
  const [open, setOpen] = useState(false);
  const fmt = spec.format ?? ((v: number) => `${fmtNum(v)}${spec.unit ? ` ${spec.unit}` : ''}`);
  return (
    <div className={compact ? undefined : 'field'} style={style}>
      {!compact && <span aria-hidden>{label}</span>}
      <button type="button" className={'input num np-field' + (value == null ? ' empty' : '')} aria-haspopup="dialog"
        aria-label={`${label}: ${value == null ? 'not set' : fmt(value)}`} onClick={() => setOpen(true)}>
        {value == null ? placeholder ?? '–' : fmt(value)}
      </button>
      <NumberSheet open={open} onClose={() => setOpen(false)} title={title ?? label} value={value} onPick={onChange} spec={spec} />
    </div>
  );
}

/** Sensible dose steps for supplement units (list + keypad). */
export function doseSpec(unit: string): NumberSpec {
  const s: Record<string, [number, number, number]> = { // step, max, decimals
    mg: [5, 5000, 2], mcg: [5, 10000, 1], g: [0.5, 100, 2], IU: [500, 50000, 0], ml: [0.05, 20, 2], units: [1, 200, 1],
    caps: [1, 20, 0], tabs: [0.5, 20, 1], drops: [1, 60, 0], scoops: [0.5, 10, 1],
  };
  const [step, max, decimals] = s[unit] ?? [1, 10000, 2];
  return { min: step, max, step, decimals, unit, keyMin: 0.001, keyMax: max * 10 };
}
